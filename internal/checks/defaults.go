package checks

import (
	"fmt"
	"strings"

	"k8s.io/apimachinery/pkg/api/resource"
)

// DefaultConfigYAML renders the built-in defaults as a commented
// configuration file: every setting with its default value, every rule with
// its default severity, and commented examples of exclusions and custom
// rules. It is generated from the code, so it never drifts.
func DefaultConfigYAML() string {
	o := DefaultOptions()
	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, format, a...) }
	list := func(v []string) string {
		if len(v) == 0 {
			return "[]"
		}
		return "[" + strings.Join(v, ", ") + "]"
	}

	w(`# oc-upkit configuration — generated by "oc upkit config default".
#
# Usage:    oc upkit --config upkit.yaml      (or UPKIT_CONFIG=upkit.yaml)
# Validate: oc upkit config validate --config upkit.yaml
#
# Precedence: built-in defaults < this file < command-line flags.
# Unknown keys are rejected to catch typos. Every value below is the default:
# delete what you do not need to change.

# ---------------------------------------------------------------------------
# settings: equivalent of the command-line flags
# ---------------------------------------------------------------------------
settings:
  failOn: crit                       # crit | warn: level giving a non-zero exit code
  # checks: [etcd, mcp, pdb]         # subset of checks (default: all)
  # skip: [csr]                      # checks to skip
  # targetVersion: 4.18.24           # validated against the update graph
  maxRows: %d
  alertSeverities: %s
  ignoreAlerts: %s
  alertmanagerURL: %s
  monitoringNamespace: %s
  etcdNamespace: %s
  etcdFragThreshold: %g                # percent of reclaimable space
  etcdDBSizeWarn: %s
  etcdExpectedMembers: %d
  zoneLabel: %s
  groupByLabels: []                  # e.g. [example.com/room, node-role.kubernetes.io/infra]
  # nodeSelector: node-role.kubernetes.io/worker
  nodePodCapacityPct: %g
  podPendingAge: %s
  podNotReadyAge: %s                   # 0s = report Running pods not ready (0/1) immediately
  podTerminatingAge: %s
  podRestartWarn: %d
  quotaThreshold: %g
  jobLongDuration: %s
  hcpFilter: []                      # hub only, globs on name or namespace/name

# ---------------------------------------------------------------------------
# severities: per-rule severity — crit | warn | info | "off"
# Globs are accepted ("pods.*": info); the most specific pattern wins.
# Quote "off": unquoted, YAML 1.1 reads it as a boolean (also accepted).
# ---------------------------------------------------------------------------
severities:
`,
		o.MaxRows, list(o.AlertSeverities), list(o.IgnoreAlerts), o.AlertmanagerURL, o.MonitoringNS,
		o.EtcdNamespace, o.EtcdFragThreshold, resource.NewQuantity(o.EtcdDBSizeWarn, resource.BinarySI).String(),
		o.EtcdExpectedMembers, o.ZoneLabel, o.NodePodCapacityPct, fmtDuration(o.PodPendingAge),
		fmtDuration(o.PodNotReadyAge), fmtDuration(o.PodTerminatingAge), o.PodRestartWarn,
		o.QuotaThreshold, fmtDuration(o.JobLongDuration))

	width := 0
	for _, r := range Catalog {
		if len(r.ID) > width {
			width = len(r.ID)
		}
	}
	check := ""
	for _, r := range Catalog {
		if r.Check != check {
			check = r.Check
			w("  # %s\n", check)
		}
		w("  %-*s %-5s # %s\n", width+1, r.ID+":", LevelName(r.Level), r.Description)
	}

	b.WriteString(`
# ---------------------------------------------------------------------------
# exclusions: ignore some objects for a rule (globs).
#   rule:       rule ID or pattern (default "*": every rule)
#   namespaces: at least one must match when set
#   names:      at least one must match when set
# ---------------------------------------------------------------------------
exclusions: []
# - rule: "pods.*"
#   namespaces: ["sandbox-*", "*-dev"]
#   reason: sandbox environments
# - rule: pdb.blocking
#   namespaces: [openshift-storage]
#   reason: managed by the ODF operator
# - rule: alerts.warning
#   names: [KubeCPUOvercommit, KubeMemoryOvercommit]

# ---------------------------------------------------------------------------
# customRules: your own rules written in CEL, the language used by
# ValidatingAdmissionPolicies. "expr" must be TRUE for a compliant object.
#
#   id                          lowercase id, usable in severities / exclusions
#   apiVersion, resource        target type (resource is plural: deployments…)
#   namespaces, labelSelector,
#   fieldSelector               server-side filtering (optional)
#   match                       CEL pre-filter (optional)
#   expr                        compliance condition (required)
#   aggregate: true             expr evaluated once on the "objects" list
#   severity                    crit | warn (default) | info | "off"
#   message, messageExpression  violation message
#   params                      values available as params.xxx
#
# Variables: object, objects, params, now (timestamp), clusterVersion,
# hostedControlPlane. Libraries: standard CEL + strings, sets, lists, math.
# Use has() for optional fields.
# ---------------------------------------------------------------------------
customRules: []
# - id: org.olm-manual-approval
#   description: OLM operators must use Manual approval in production
#   apiVersion: operators.coreos.com/v1alpha1
#   resource: subscriptions
#   expr: 'has(object.spec.installPlanApproval) && object.spec.installPlanApproval == "Manual"'
#   messageExpression: '"Subscription " + object.spec.name + " uses Automatic approval"'
#
# - id: org.deploy-min-replicas
#   description: Application Deployments need at least 2 replicas to survive a drain
#   apiVersion: apps/v1
#   resource: deployments
#   match: '!object.metadata.namespace.startsWith("openshift-") && !object.metadata.namespace.startsWith("kube-")'
#   expr: '!has(object.spec.replicas) || object.spec.replicas == 0 || object.spec.replicas >= params.minReplicas'
#   messageExpression: '"single replica: " + object.metadata.name + " will be unavailable during the drain"'
#   params:
#     minReplicas: 2
#
# - id: org.pvc-pending
#   description: No PVC Pending for more than 10 minutes
#   apiVersion: v1
#   resource: persistentvolumeclaims
#   expr: 'object.status.phase != "Pending" || now - timestamp(object.metadata.creationTimestamp) < duration("10m")'
#   message: PVC Pending for more than 10 minutes
#
# - id: org.no-node-in-maintenance
#   description: No node may carry the maintenance label before the upgrade
#   apiVersion: v1
#   resource: nodes
#   labelSelector: example.com/maintenance=true
#   aggregate: true
#   expr: size(objects) == 0
#   messageExpression: '"nodes in maintenance: " + objects.map(n, n.metadata.name).join(", ")'
#   severity: crit
`)
	return b.String()
}
